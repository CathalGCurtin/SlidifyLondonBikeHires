testthat::test_that("browser updates dates, chart, and validation messages", {
  testthat::skip_if(Sys.getenv("RUN_BROWSER_TESTS") != "true", "Set RUN_BROWSER_TESTS=true for browser checks")
  app <- shinytest2::AppDriver$new(app_dir = root, name = "bike-hires", width = 1280, height = 900)
  on.exit(app$stop())
  testthat::expect_match(app$get_value(output = "selected_range"), "1,675 days")
  # Compare rendered pixels, not the image URL (which may change on every render).
  plot_pixels <- function() app$get_js("(() => { const img = document.querySelector('#history img'); const canvas = document.createElement('canvas'); canvas.width = img.naturalWidth; canvas.height = img.naturalHeight; canvas.getContext('2d').drawImage(img, 0, 0); return canvas.toDataURL(); })()")
  full_history <- plot_pixels()
  app$set_inputs(dates = c("2012-03-01", "2012-03-31"))
  testthat::expect_equal(app$get_value(output = "mean_hires"), "26,394")
  testthat::expect_match(app$get_value(output = "selected_range"), "31 days")
  testthat::expect_true(app$get_js("(() => { const img = document.querySelector('#history img'); return !!img && img.complete && img.naturalWidth > 0; })()"))
  march_history <- plot_pixels()
  testthat::expect_false(identical(full_history, march_history))
  app$set_inputs(dates = c("2010-07-30", "2015-02-28"))
  testthat::expect_identical(plot_pixels(), full_history)
  app$set_inputs(dates = c("2012-03-01", "2012-03-31"))
  testthat::expect_identical(plot_pixels(), march_history)
  # Bypass the datepicker's bounds/order restrictions to exercise server defenses.
  app$run_js("Shiny.setInputValue('dates', ['2012-03-31','2012-03-01'], {priority:'event'});")
  app$wait_for_idle()
  testthat::expect_match(app$get_js("document.querySelector('#mean_hires').textContent"), "on or before")
  app$run_js("Shiny.setInputValue('dates', [null,null], {priority:'event'});")
  app$wait_for_idle()
  testthat::expect_match(app$get_js("document.querySelector('#mean_hires').textContent"), "Choose both")
  app$set_inputs(dates = c("2010-07-30", "2010-07-30"))
  testthat::expect_equal(app$get_value(output = "mean_hires"), "6,897")
  app$set_window_size(390, 844)
  testthat::expect_false(app$get_js("document.documentElement.scrollWidth > window.innerWidth"))
  app$set_inputs(dates = c("2012-02-28", "2012-03-01"))
  testthat::expect_match(app$get_value(output = "selected_range"), "3 days")
  testthat::expect_true(app$get_js("(() => { const img = document.querySelector('#history img'); return !!img && img.complete && img.naturalWidth > 0; })()"))
})
